package com.webforj.bbj.security.model;

/**
 * BBjPermissions
 */
public enum BBjPermissions {
  USER, ADD_USER, ATTACH_EXISTING_DB, SET_PERMISSIONS, BBJ_PROCESSES, CREATE_TRIGGER, REMOVE_USER, CREATE_NEW_DB, ADMIN_ACCESS, SET_PASSWORDS, DROP_DB, SQL_CONNECTIONS, SERVER_CONFIG, CONNECTION_POOLS, COPY_JOBS, TABLE_ANALYSIS_QUEUE, FORCE_CLOSE_FILES, REPLICATION, SCHEDULING, AUDITING, ASYNCH_TRIGGER, DOCUMENT_ARCHIVES, EMAIL_SERVICES, METRICS, FILE_MANAGER, VIEW_OPEN_FILES;

  @Override
  public String toString() {
    return this.name().toLowerCase().replace('_', '-');
  }

}
